    #[test]
    fn unchanged_files_are_not_read_again_and_the_snapshot_is_reused() {
        let (_dir, root) = project();
        let mut indexer = WorkspaceIndexer::default();
        let first = indexer.rebuild(&root, &[]);
        let second = indexer.rebuild(&root, &[]);
        assert!(Arc::ptr_eq(&first, &second), "nothing changed");

        // A buffer with new text re-parses that one document.
        let buffer = FileBuffer {
            path: root.join("Pack/a.item.yml"),
            text: "type: item\nitems:\n  - id: Beta\n    parent: /Script/FactoryGame.FGItemDescriptor\n"
                .into(),
        };
        let third = indexer.rebuild(&root, std::slice::from_ref(&buffer));
        assert!(!Arc::ptr_eq(&second, &third));
        assert!(third.class_of_pack("Pack", "Beta").is_some());
        assert!(third.class_of_pack("Pack", "Alpha").is_none());
        let again = indexer.rebuild(&root, std::slice::from_ref(&buffer));
        assert!(Arc::ptr_eq(&third, &again), "same buffer text");

        // Closing the buffer falls back to the file on disk.
        let closed = indexer.rebuild(&root, &[]);
        assert!(closed.class_of_pack("Pack", "Alpha").is_some());
    }


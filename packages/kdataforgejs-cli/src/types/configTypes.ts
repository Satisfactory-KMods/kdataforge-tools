import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { isScalar, parseDocument } from "yaml";
import { formatGeneratedContent } from "./format.js";
import { assertSafeWrite, commitStaged, stageTexts } from "../pack/transaction.js";

const CONFIG_ID = /^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$/u;
const MAX_CONFIG_FILES = 256;
const MAX_FIELDS = 1024;
const MAX_DIRECTORY_DEPTH = 16;
type ConfigField = Readonly<Record<string, unknown>>;
const GENERATED = "// Generated by kdf sync. Do not edit.";
interface GeneratedFile { readonly path: string; readonly content: string }

/** Emits pack-local keys only; a generated map never grants config access to a script. */
export function syncConfigTypes(packRoot: string): string {
	const output = generateConfigTypes(packRoot);
	const files = [output, ...output.runtimeFiles];
	for (const file of files) assertSafeWrite(packRoot, file.path);
	commitStaged(stageTexts(files.filter((file) => !existsSync(file.path) || readFileSync(file.path, "utf8") !== file.content)));
	return output.path;
}

export function generateConfigTypes(packRoot: string): GeneratedFile & { readonly runtimeFiles: readonly GeneratedFile[] } {
	const fields = new Map<string, string>();
	const enums: string[] = [];
	for (const path of configFiles(packRoot)) {
		const yaml = parseDocument(readFileSync(path, "utf8"), { intAsBigInt: true });
		if (yaml.errors.length > 0) throw new Error(`Invalid config YAML: ${path}`);
		const document: unknown = yaml.toJS();
		const entries = asRecord(document)?.fields;
		if (!Array.isArray(entries)) continue;
		for (const [index, entry] of entries.entries()) {
			const field = asRecord(entry);
			if (field === undefined || typeof field.id !== "string" || !CONFIG_ID.test(field.id)) throw new Error(`Invalid config id in ${path}.`);
			if (fields.has(field.id)) throw new Error(`Duplicate config id '${field.id}'.`);
			if (fields.size >= MAX_FIELDS) throw new Error("Config type generation exceeds field limit.");
			const options = Array.isArray(field.options) ? field.options.map((option, optionIndex) => {
				const scalar = yaml.getIn(["fields", index, "options", optionIndex, "value"], true);
				return { ...asRecord(option), value: isScalar(scalar) && typeof scalar.value !== "string" ? scalar.source ?? scalar.value : asRecord(option)?.value };
			}) : field.options;
			const selection = field.type === "select" ? selectionEnum({ ...field, options }) : undefined;
			if (selection) enums.push(selection.declaration);
			const scalar = selection ? `import("../scripts/generated/kdataforgejs-config-enums").${selection.name}` : fieldType({ ...field, multiple: false });
			fields.set(field.id, field.multiple === true ? `readonly (${scalar})[]` : scalar);
		}
	}
	const path = join(packRoot, "typescript/kdataforgejs-config.d.ts");
	const entries = [...fields].sort(([left], [right]) => left.localeCompare(right))
		.map(([id, type]) => `readonly ${JSON.stringify(id)}: ${type};`).join("\n");
	const content = formatGeneratedContent(`${GENERATED}\ndeclare module "@sf-kmods/kdataforgejs" { export interface ConfigValueMap {\n${entries}\n} }\n`, path);
	const runtimePath = join(packRoot, "scripts/generated/kdataforgejs-config-enums.ts");
	assertSafeWrite(packRoot, runtimePath);
	if (existsSync(runtimePath) && !readFileSync(runtimePath, "utf8").startsWith(GENERATED)) throw new Error(`Refusing to overwrite authored file: ${runtimePath}`);
	const runtimeContent = formatGeneratedContent(`${GENERATED}\n${enums.sort().join("\n")}\nexport {};\n`, runtimePath);
	if (Buffer.byteLength(runtimeContent) > 256 * 1024) throw new Error("Generated config enums exceed the script module byte limit.");
	return { path, content, runtimeFiles: [{ path: runtimePath, content: runtimeContent }] };
}

function selectionEnum(field: ConfigField): { readonly name: string; readonly declaration: string } {
	if (!Array.isArray(field.options) || field.options.length === 0 || field.options.length > 1024) throw new Error(`Select '${String(field.id)}' requires 1–1024 static options.`);
	const id = String(field.id);
	const name = `Config${id.split(/[^A-Za-z0-9]+/u).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("")}_${createHash("sha256").update(id).digest("hex").slice(0, 8)}`;
	const values = field.options.map((option) => choiceValue(asRecord(option)?.value, String(field.valueType ?? "string").trim().toLowerCase()));
	const names = new Set<string>();
	const members = values.map((value, index) => {
		const stem = typeof value === "string" ? value.split(/[^A-Za-z0-9]+/u).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("") : `Value${index}`;
		let member = /^[A-Za-z][A-Za-z0-9]*$/u.test(stem) ? stem : `Value${index}`;
		if (["constructor", "prototype", "__proto__"].includes(member) || names.has(member)) member = `Value${index}_${createHash("sha256").update(String(value)).digest("hex").slice(0, 8)}`;
		names.add(member);
		return `${member}: ${typeof value === "bigint" ? `${value}n` : JSON.stringify(value)}`;
	});
	if (values.every((value) => typeof value === "string" || typeof value === "number")) return { name, declaration: `export enum ${name} { ${members.map((entry) => entry.replace(": ", " = ")).join(", ")} }` };
	return { name, declaration: `export const ${name} = Object.freeze({ ${members.join(", ")} } as const);\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];` };
}

function choiceValue(value: unknown, type: string): string | number | bigint | boolean {
	if (!["string", "number", "bigint", "boolean"].includes(typeof value)) throw new Error("Config option values must be scalar.");
	const text = String(value);
	if (["string", "text", "name", "tag"].includes(type)) return text;
	if (type === "bool") {
		if (["true", "yes", "on", "1"].includes(text.trim().toLowerCase())) return true;
		if (["false", "no", "off", "0"].includes(text.trim().toLowerCase())) return false;
		throw new Error(`Invalid boolean config option '${text}'.`);
	}
	if (["int8", "int16", "int32", "int64", "uint8"].includes(type)) {
		if (!/^[+-]?\d+$/u.test(text)) throw new Error(`Invalid integer config option '${text}'.`);
		const integer = BigInt(text);
		if (integer < -(2n ** 63n) || integer > 2n ** 63n - 1n) throw new Error("Config option is outside int64 range.");
		return integer >= BigInt(Number.MIN_SAFE_INTEGER) && integer <= BigInt(Number.MAX_SAFE_INTEGER) ? Number(integer) : integer;
	}
	if (["float", "double"].includes(type) && text.trim() !== "" && Number.isFinite(Number(text))) return Number(text);
	throw new Error(`Unsupported config option valueType '${type}'.`);
}

function configFiles(root: string): string[] {
	const result: string[] = [];
	const visit = (directory: string, depth: number): void => {
		if (depth > MAX_DIRECTORY_DEPTH) throw new Error("Config type generation exceeds directory depth limit.");
		for (const entry of readdirSync(directory, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
			if (entry.isSymbolicLink() || entry.name === "typescript" || entry.name.startsWith(".")) continue;
			const path = join(directory, entry.name);
			if (entry.isDirectory()) visit(path, depth + 1);
			else if (entry.isFile() && /\.config\.ya?ml$/iu.test(entry.name)) {
				if (result.length >= MAX_CONFIG_FILES) throw new Error("Config type generation exceeds file limit.");
				result.push(path);
			}
		}
	};
	visit(root, 0);
	return result;
}

function fieldType(field: ConfigField): string {
	let scalar: string;
	const valueType = String(field.valueType ?? "").trim().toLowerCase();
	if (field.type === "boolean" || valueType === "bool") scalar = "boolean";
	else if (field.type === "number" || ["int8", "int16", "int32", "int64", "uint8", "float", "double"].includes(valueType)) scalar = valueType === "int64" ? "number | bigint" : "number";
	else if (field.type === "text" || field.type === "select") scalar = "string";
	else throw new Error(`Unsupported config field type '${String(field.type)}'.`);
	return field.multiple === true ? `readonly (${scalar})[]` : scalar;
}

function asRecord(value: unknown): ConfigField | undefined {
	return typeof value === "object" && value !== null && !Array.isArray(value) ? value as ConfigField : undefined;
}
